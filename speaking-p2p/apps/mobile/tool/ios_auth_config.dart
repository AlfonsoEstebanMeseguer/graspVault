// Writes ios/Flutter/Auth.xcconfig from env/dev.json (D-062) so Info.plist's
// Google URL scheme always matches GOOGLE_IOS_CLIENT_ID: one source of truth.
// Run from apps/mobile:  dart run tool/ios_auth_config.dart [env/dev.json]
// The iOS workflow runs it before `flutter build ios`. Client IDs are public.
import 'dart:convert';
import 'dart:io';

/// "123-abc.apps.googleusercontent.com" -> "com.googleusercontent.apps.123-abc".
String reversedClientId(String clientId) {
  const suffix = '.apps.googleusercontent.com';
  if (!clientId.endsWith(suffix)) {
    throw const FormatException('GOOGLE_IOS_CLIENT_ID must end with $suffix (is it the client secret?)');
  }
  return 'com.googleusercontent.apps.${clientId.substring(0, clientId.length - suffix.length)}';
}

void main(List<String> args) {
  final envPath = args.isEmpty ? 'env/dev.json' : args.first;
  final defines = jsonDecode(File(envPath).readAsStringSync()) as Map<String, dynamic>;
  final id = (defines['GOOGLE_IOS_CLIENT_ID'] as String? ?? '').trim();
  final out = File('ios/Flutter/Auth.xcconfig');
  // xcconfig treats "//" as a comment; client IDs never contain it.
  final value = id.isEmpty ? '' : reversedClientId(id);
  out.writeAsStringSync('// Generated by tool/ios_auth_config.dart from $envPath. Do not edit.\n'
      'GOOGLE_REVERSED_CLIENT_ID=$value\n');
  stdout.writeln(id.isEmpty ? 'GOOGLE_IOS_CLIENT_ID not set: Google Sign-In stays off on iOS.' : 'Auth.xcconfig: URL scheme set.');
}
