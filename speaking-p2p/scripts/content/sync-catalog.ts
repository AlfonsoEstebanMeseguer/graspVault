// Generates apps/backend/supabase/seed/exam_catalog.sql from content/.
// The server never reads the exam JSON: it needs id/level/version and the
// precomputed timeline. CI fails if this file is stale (content_test.ts).
// deno run --allow-read --allow-write scripts/content/sync-catalog.ts
import { loadContent } from "./lib.ts";
import { buildTimeline } from "../../apps/backend/supabase/functions/_shared/exam/timeline.ts";

export async function catalogSql(): Promise<string> {
  const { index, exams, errors } = await loadContent();
  if (errors.length) throw new Error(`content invalid:\n${errors.join("\n")}`);
  const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
  const rows = exams.map((e) => {
    const t = buildTimeline(e);
    return `  (${q(e.id)}, ${q(e.level)}, ${e.version}, ${index.version}, ${q(JSON.stringify(t))}::jsonb, ${t.totalMs}, true)`;
  });
  return [
    "-- GENERATED by scripts/content/sync-catalog.ts. Do not edit by hand.",
    "insert into public.exam_catalog (id, level, version, content_version, timeline, total_ms, active) values",
    rows.join(",\n"),
    "on conflict (id) do update set level = excluded.level, version = excluded.version,",
    "  content_version = excluded.content_version, timeline = excluded.timeline,",
    "  total_ms = excluded.total_ms, active = excluded.active;",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const out = new URL("../../apps/backend/supabase/seed/exam_catalog.sql", import.meta.url);
  await Deno.writeTextFile(out, await catalogSql());
  console.log(`wrote ${out.pathname}`);
}
